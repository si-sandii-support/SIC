import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import { convertRouter } from "./routes/convert.js";
import { shareRouter } from "./routes/share.js";
import { validateRouter } from "./routes/validate.js";
import { renderRouter } from "./routes/render.js";
const app = express();
const port = Number(process.env.PORT || 4000);
app.use(helmet());
app.use(cors({ origin: (process.env.CORS_ORIGIN || "http://localhost:5173").split(",") }));
app.use(express.raw({ type: ["application/octet-stream", "application/vnd.openxmlformats-officedocument.presentationml.presentation"], limit: `${process.env.MAX_BODY_MB || 50}mb` }));
app.use(express.json({ limit: `${process.env.MAX_BODY_MB || 50}mb` }));
app.use(rateLimit({ windowMs: 60000, limit: 120 }));
app.get("/health", (_req, res) => res.json({ ok: true, service: "sī-document-api" }));
app.use("/api/convert", convertRouter);
app.use("/api/share", shareRouter);
app.use("/api/validate", validateRouter);
app.use("/api/render", renderRouter);
app.use((err, _req, res, _next) => { console.error(err); res.status(500).json({ error: err instanceof Error ? err.message : "Unexpected server error." }); });
app.listen(port, () => console.log(`API listening on http://localhost:${port}`));
